//! The tokens of a state diagram, as Pele's tokens.ts has them.

/// A token's type, Pele's T. The names are Pele's as they are, as the grammar's are.
#[allow(
    non_camel_case_types,
    clippy::upper_case_acronyms,
    clippy::enum_variant_names
)]
