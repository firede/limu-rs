impl T {
    /// The type's name, as Jison's errors give it.
    pub(crate) fn name(self) -> &'static str {
        TOKEN_NAMES[self as usize]
    }
}

/// The longest keyword, in characters, Pele's LONGEST_KEYWORD.
pub(crate) const LONGEST_KEYWORD: usize = 22;

/// The keyword a word is, written in lower case, as Pele's KEYWORDS finds it. Every keyword
/// is matched without regard to case and ends at a word boundary.
pub(crate) fn keyword(lower: &str) -> Option<T> {
    Some(match lower {
        "requirementdiagram" => T::RD,
        "id" => T::ID,
        "text" => T::TEXT,
        "risk" => T::RISK,
        "verifymethod" => T::VERIFYMTHD,
        "requirement" => T::REQUIREMENT,
        "functionalrequirement" => T::FUNCTIONAL_REQUIREMENT,
        "interfacerequirement" => T::INTERFACE_REQUIREMENT,
        "performancerequirement" => T::PERFORMANCE_REQUIREMENT,
        "physicalrequirement" => T::PHYSICAL_REQUIREMENT,
        "designconstraint" => T::DESIGN_CONSTRAINT,
        "low" => T::LOW_RISK,
        "medium" => T::MED_RISK,
        "high" => T::HIGH_RISK,
        "analysis" => T::VERIFY_ANALYSIS,
        "demonstration" => T::VERIFY_DEMONSTRATION,
        "inspection" => T::VERIFY_INSPECTION,
        "test" => T::VERIFY_TEST,
        "element" => T::ELEMENT,
        "contains" => T::CONTAINS,
        "copies" => T::COPIES,
        "derives" => T::DERIVES,
        "satisfies" => T::SATISFIES,
        "verifies" => T::VERIFIES,
        "refines" => T::REFINES,
        "traces" => T::TRACES,
        "type" => T::TYPE,
        "docref" => T::DOCREF,
        "style" => T::STYLE,
        "classdef" => T::CLASSDEF,
        "class" => T::CLASS,
        _ => return None,
    })
}
